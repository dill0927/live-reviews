CREATE OR REPLACE FUNCTION "public"."search_venues"("query" "text") RETURNS TABLE("id" "uuid", "name" "text")
    LANGUAGE "sql" STABLE
    AS $$
  select id, name
  from venues
  where similarity(name, query) > 0.1 -- 類似度が 0.3 以上の会場を取得
  order by similarity(name, query) desc
  limit 5;
$$;


